const DICTIONARIES = {
  en: EN_TRANSLATIONS,
  fr: FR_TRANSLATIONS,
  pt: PT_TRANSLATIONS,
  de: DE_TRANSLATIONS,
  it: IT_TRANSLATIONS,
};

const FRAGMENTS = {
  en: EN_FRAGMENT_TRANSLATIONS,
  fr: FR_FRAGMENT_TRANSLATIONS,
  pt: PT_FRAGMENT_TRANSLATIONS,
  de: DE_FRAGMENT_TRANSLATIONS,
  it: IT_FRAGMENT_TRANSLATIONS,
};

const originalTextByNode = new WeakMap();
const originalAttrByNode = new WeakMap();

function normalizeLanguage(language) {
  const safeLanguage = typeof language === 'string' ? language.trim().toLowerCase() : SOURCE_LANGUAGE;
  if (safeLanguage === SOURCE_LANGUAGE) {
    return SOURCE_LANGUAGE;
  }

  return DICTIONARIES[safeLanguage] ? safeLanguage : SOURCE_LANGUAGE;
}

function translateCoreText(value, language) {
  if (!value || language === SOURCE_LANGUAGE) {
    return value;
  }

  const dictionary = DICTIONARIES[language];
  if (dictionary[value]) {
    return dictionary[value];
  }

  // Keep native dictionaries as priority, but avoid raw Spanish text leaks
  // by falling back to English when a key is still pending in that language.
  if (language !== 'en' && EN_TRANSLATIONS[value]) {
    return EN_TRANSLATIONS[value];
  }

  let translatedValue = value;
  const fragments = [...(FRAGMENTS[language] || [])];
  if (language !== 'en') {
    fragments.push(...EN_FRAGMENT_TRANSLATIONS);
  }

  fragments.forEach(([sourceText, targetText]) => {
    if (translatedValue.includes(sourceText)) {
      translatedValue = translatedValue.replaceAll(sourceText, targetText);
    }
  });

  return translatedValue;
}

export function translateUiText(value, language) {
  if (typeof value !== 'string') {
    return value;
  }

  return translateCoreText(value, normalizeLanguage(language));
}

function translateWithPadding(value, language) {
  if (typeof value !== 'string') {
    return value;
  }

  const match = value.match(/^(\s*)(.*?)(\s*)$/s);
  if (!match) {
    return value;
  }

  const [, prefix, core, suffix] = match;
  if (!core) {
    return value;
  }

  return `${prefix}${translateCoreText(core, language)}${suffix}`;
}

function setTranslatedTextNode(textNode, language) {
  if (!originalTextByNode.has(textNode)) {
    originalTextByNode.set(textNode, textNode.nodeValue || '');
  }

  const originalValue = originalTextByNode.get(textNode) || '';
  const translatedValue = translateWithPadding(originalValue, language);

  if (textNode.nodeValue !== translatedValue) {
    textNode.nodeValue = translatedValue;
  }
}

function setTranslatedAttribute(element, attributeName, language) {
  const currentValue = element.getAttribute(attributeName);
  if (typeof currentValue !== 'string') {
    return;
  }

  let originalAttributes = originalAttrByNode.get(element);
  if (!originalAttributes) {
    originalAttributes = {};
    originalAttrByNode.set(element, originalAttributes);
  }

  if (!(attributeName in originalAttributes)) {
    originalAttributes[attributeName] = currentValue;
  }

  const translatedValue = translateWithPadding(originalAttributes[attributeName], language);
  if (currentValue !== translatedValue) {
    element.setAttribute(attributeName, translatedValue);
  }
}

export function translateUiTree(rootElement, language) {
  if (!rootElement) {
    return;
  }

  const normalizedLanguage = normalizeLanguage(language);
  const walker = document.createTreeWalker(rootElement, NodeFilter.SHOW_TEXT);

  while (walker.nextNode()) {
    const textNode = walker.currentNode;
    if (!textNode) {
      continue;
    }

    const parentTag = textNode.parentElement?.tagName;
    if (parentTag === 'SCRIPT' || parentTag === 'STYLE') {
      continue;
    }

    if (!textNode.nodeValue?.trim()) {
      continue;
    }

    setTranslatedTextNode(textNode, normalizedLanguage);
  }

  rootElement.querySelectorAll('[placeholder], [title], [aria-label]').forEach((element) => {
    setTranslatedAttribute(element, 'placeholder', normalizedLanguage);
    setTranslatedAttribute(element, 'title', normalizedLanguage);
    setTranslatedAttribute(element, 'aria-label', normalizedLanguage);
  });
}
